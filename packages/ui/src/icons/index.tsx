export type AppIconProps = Omit<LucideProps, 'size'> & {
  size?: number
  style?: CSSProperties
}

export type AppIcon = (props: AppIconProps) => ReactElement

function icon(Icon: LucideIcon, defaultStrokeWidth = 1.75): AppIcon {
  return function AppIcon({
    size = 16,
    strokeWidth = defaultStrokeWidth,
    absoluteStrokeWidth = true,
    ...props
  }: AppIconProps) {
    return (
      <Icon
        size={size}
        strokeWidth={strokeWidth}
        absoluteStrokeWidth={absoluteStrokeWidth}
        aria-hidden="true"
        focusable="false"
        {...props}
      />
    )
  }
}

