import assert from 'node:assert/strict'
import test from 'node:test'
import {
  buildVerificationUrl,
  renderAuthEmailHtml,
} from '../supabase/functions/send-email-hook/email-template'

const input = {
  actionType: 'magiclink',
  token: '12345678',
  tokenHash: 'hashed-token',
  redirectTo: 'https://app.masabu.co/auth/callback?next=%2Fdashboard',
  supabaseUrl: 'https://svxvloeosiksqfadgkvo.supabase.co',
}

test('send-email hook builds a production verification link for magic-link login', () => {
  const result = buildVerificationUrl(input)
  assert.ok(result)

  const url = new URL(result)
  assert.equal(url.origin, input.supabaseUrl)
  assert.equal(url.pathname, '/auth/v1/verify')
  assert.equal(url.searchParams.get('token'), input.tokenHash)
  assert.equal(url.searchParams.get('type'), 'magiclink')
  assert.equal(url.searchParams.get('redirect_to'), input.redirectTo)
})

test('send-email hook renders dashboard login with a link and no unnecessary code', () => {
  const html = renderAuthEmailHtml(input)
  assert.match(html, />Güvenli giriş yap<\/a>/)
  assert.doesNotMatch(html, /12345678|TEK KULLANIMLIK KOD|Kodunuzun|kodunuzu/i)
  assert.match(html, /redirect_to=https%3A%2F%2Fapp\.masabu\.co/)
  assert.doesNotMatch(html, /&redirect_to=/)
})

test('send-email hook keeps code-only actions free of misleading links', () => {
  const html = renderAuthEmailHtml({ ...input, actionType: 'otp' })
  assert.doesNotMatch(html, /auth\/v1\/verify|auth\/confirm|Güvenli giriş yap/)
  assert.match(html, /tek kullanımlık kodu/)
})

test('send-email hook refuses non-HTTPS verification origins', () => {
  assert.equal(buildVerificationUrl({ ...input, supabaseUrl: 'http://localhost:54321' }), null)
})

test('the deployable Deno brand module matches the single authored source', async () => {
  const { readFile } = await import('node:fs/promises')
  const source = await readFile(new URL('../../domain/src/email-brand.ts', import.meta.url), 'utf8')
  const generated = await readFile(new URL('../supabase/functions/_shared/email-brand.ts', import.meta.url), 'utf8')
  assert.equal(generated, '// Generated by pnpm email:sync. Edit packages/domain/src/email-brand.ts instead.\n' + source, 'Run pnpm email:sync before deploying the Auth hook')
})

test('link-only account actions omit codes and code-related instructions in HTML and text', async () => {
  const { renderAuthEmailText } = await import('../supabase/functions/send-email-hook/email-template')
  for (const actionType of ['recovery', 'invite', 'email_change', 'magiclink']) {
    const args = { ...input, actionType, redirectTo: 'https://app.masabu.co/auth/confirm' }
    for (const rendered of [renderAuthEmailHtml(args), renderAuthEmailText(args)]) {
      assert.doesNotMatch(rendered, /12345678|kod|10 dakika/i, actionType)
      assert.match(rendered, /https:/, actionType)
    }
  }
})

test('menu OTP login and signup keep their codes without offering a competing link', () => {
  for (const actionType of ['magiclink', 'signup', 'otp', 'reauthentication']) {
    for (const redirectTo of ['', 'https://app.masabu.co', 'https://menu.masabu.co/auth/callback']) {
      const html = renderAuthEmailHtml({ ...input, actionType, redirectTo })
      assert.match(html, />12345678<\/span>/)
      assert.doesNotMatch(html, /auth\/v1\/verify|auth\/confirm|10 dakika/)
    }
  }
})

test('missing link configuration cannot silently send a code for a link-only action', () => {
  assert.throws(() => renderAuthEmailHtml({ ...input, actionType: 'invite', tokenHash: '' }), /verification URL unavailable/)
})
