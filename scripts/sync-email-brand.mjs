import { mkdir, readFile, writeFile } from 'node:fs/promises'

// Keep the independently deployed Deno function self-contained. The domain module
// remains the only authored source; the DB parity test catches a stale generated copy.
const source = await readFile(new URL('../packages/domain/src/email-brand.ts', import.meta.url), 'utf8')
const directory = new URL('../packages/db/supabase/functions/_shared/', import.meta.url)
await mkdir(directory, { recursive: true })
await writeFile(new URL('email-brand.ts', directory), '// Generated by pnpm email:sync. Edit packages/domain/src/email-brand.ts instead.\n' + source)
