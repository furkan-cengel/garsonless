test('contact form supports general, sales and support messages with guarded delivery', () => {
  for (const name of ['name', 'email', 'topic', 'phone', 'businessName', 'branchCount', 'message', 'website']) {
    assert.match(form, new RegExp(`name=["{]?["']?${name}`))
  }
  for (const topic of ['general', 'sales', 'support']) assert.match(form, new RegExp(`value="${topic}"`))
  assert.match(form, /from '\.\/ui\/Select'/)
  assert.match(form, /<Select name="topic"/)
  assert.doesNotMatch(form, /<select name="topic"/)
  assert.match(form, /role=\{state\.kind === 'error' \? 'alert' : 'status'\}/)
  assert.match(form, /NEXT_PUBLIC_RECAPTCHA_SITE_KEY/)
  assert.match(form, /google\.com\/recaptcha\/api\.js\?render=explicit/)
  assert.match(form, /recaptchaToken: captchaToken/)
  assert.match(endpoint, /api\.resend\.com\/emails/)
  assert.match(endpoint, /google\.com\/recaptcha\/api\/siteverify/)
  assert.match(endpoint, /RECAPTCHA_SECRET_KEY/)
  assert.match(endpoint, /if \(contact\.website\)/)
  assert.match(endpoint, /consumeDashboardAuthRateLimit/)
  assert.match(endpoint, /limit: 3/)
  assert.match(endpoint, /!rateLimit\.allowed/)
  assert.match(endpoint, /result\.hostname === expectedHostname/)
  assert.match(endpoint, /AbortSignal\.timeout\(10_000\)/)
  assert.match(legacyEndpoint, /export const runtime = 'nodejs'/)
  assert.match(legacyEndpoint, /export \{ POST \} from '\.\.\/route'/)
  assert.match(contact, /id="satis-formu"/)
  assert.match(contact, /<BusinessContactForm \/>/)
  assert.match(contact, /contact-page__grid/)
})
