import { mkdirSync, writeFileSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import { chromium, expect as playwrightExpect } from '@playwright/test'
import { createClient } from '@supabase/supabase-js'
const expect = playwrightExpect.configure({ timeout: 30000 })
const base = process.env['MENU_BULK_BROWSER_BASE'] ?? 'http://localhost:3000'
const url = process.env['NEXT_PUBLIC_SUPABASE_URL']!
if (new URL(url).hostname !== 'yxsegwkzyiscrxiwdeuf.supabase.co' || !['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw new Error('DEV localhost only')
const admin = createClient(url, process.env['SUPABASE_SERVICE_ROLE_KEY']!, { auth: { persistSession: false, autoRefreshToken: false } })
const { data: sourceRestaurant, error } = await admin.from('restaurants').select('id,owner_id,slug').eq('slug','test-cafe-b').single()
if (error || !sourceRestaurant) throw new Error('DEV restaurant missing')
const restaurant = { id: randomUUID(), owner_id: sourceRestaurant.owner_id, slug: `bulk-browser-${randomUUID()}` }
const { data: owner } = await admin.auth.admin.getUserById(restaurant.owner_id)
const link = await admin.auth.admin.generateLink({ type: 'magiclink', email: owner.user!.email! })
if (link.error) throw new Error('Test auth unavailable')
const authClient = createClient(url, process.env['NEXT_PUBLIC_SUPABASE_ANON_KEY']!, { auth: { persistSession: false, autoRefreshToken: false } })
const auth = await authClient.auth.verifyOtp({ token_hash: link.data.properties.hashed_token, type: 'email' })
if (auth.error || !auth.data.session) throw new Error('Test auth failed')
const categoryId = randomUUID(), secondCategoryId = randomUUID(), prefix = `Bulk ${randomUUID().slice(0,8)}`
const output = '/private/tmp/masabu-menu-bulk-browser'
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const errors: string[] = []
try {
  const fixture = await admin.from('restaurants').insert({ ...restaurant, name: 'Bulk Browser Fixture', plan: 'starter' })
  if (fixture.error) throw fixture.error
  const subscription = await admin.from('billing_subscriptions').insert({ restaurant_id: restaurant.id, plan: 'starter', status: 'trial', provider: null, trial_ends_at: new Date(Date.now()+86400000).toISOString(), billing_interval: 'monthly' })
  if (subscription.error) throw subscription.error
  const category = await admin.from('menu_categories').insert([{ id: categoryId, restaurant_id: restaurant.id, name: `${prefix} A` }, { id: secondCategoryId, restaurant_id: restaurant.id, name: `${prefix} B` }])
  if (category.error) throw category.error
  const seeded = await admin.from('menu_items').insert(Array.from({ length: 70 }, (_,index) => ({ category_id: index < 35 ? categoryId : secondCategoryId, name: `${prefix} ${String(index).padStart(2,'0')}`, price: 100, description: 'Deneme açıklaması', position: index }))).select('*').order('position')
  if (seeded.error) throw seeded.error
  const first = seeded.data[0]!
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  await context.addCookies([{ name: 'sb-yxsegwkzyiscrxiwdeuf-auth-token', value: `base64-${Buffer.from(JSON.stringify(auth.data.session)).toString('base64url')}`, url: base, sameSite: 'Lax' }])
  const page = await context.newPage()
  page.setDefaultTimeout(30000)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}/dashboard/${restaurant.id}/menu`, { waitUntil: 'domcontentloaded', timeout: 60000 })
  const publicUrl = `http://localhost:3011/${restaurant.slug}/menu`
  const publicBefore = await fetch(publicUrl)
  if (!publicBefore.ok || !(await publicBefore.text()).includes(first.name)) throw new Error('Public menu fixture unavailable')
  await page.getByRole('textbox', { name: 'Ürün veya kategori ara' }).fill(`${prefix} 00`)
  await page.getByRole('button', { name: 'Tüm ürünleri düzenle (70)', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Toplu düzenle', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('70 ürün · 2 kategori', { exact: true })).toBeVisible()
  await expect(dialog.getByText('Tüm menü', { exact: true })).toBeVisible()
  console.log('All products across categories opened despite restricted search')
  await dialog.getByLabel('Tutar / oran', { exact: true }).fill('10')
  await dialog.getByRole('button', { name: '70 ürüne uygula', exact: true }).click()
  await expect(dialog.locator(`#bulk-price-${first.id}`)).toHaveValue('110,00')
  await dialog.locator(`#bulk-name-${first.id}`).fill(`${prefix} Özel`)
  await dialog.getByRole('button', { name: 'Kapat', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('button', { name: 'Düzenlemeye dön', exact: true }).click()
  await expect(dialog.locator(`#bulk-name-${first.id}`)).toHaveValue(`${prefix} Özel`)
  await page.screenshot({ path: `${output}/desktop-edit.png` })
  await dialog.getByRole('button', { name: 'Değişiklikleri incele', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '70 ürünü güncelle', exact: true })).toBeVisible({ timeout: 30000 })
  await page.screenshot({ path: `${output}/desktop-preview.png` })
  console.log('Desktop preview passed')
  await dialog.getByRole('button', { name: '70 ürünü güncelle', exact: true }).click()
  await expect(dialog).toHaveCount(0, { timeout: 30000 })
  const rows = await admin.from('menu_items').select('id,price,name').in('category_id',[categoryId,secondCategoryId])
  if (rows.error || rows.data.length !== 70 || rows.data.some(row => row.price !== 110)) throw new Error('Bulk commit failed')
  const publicAfter = await fetch(publicUrl)
  if (!publicAfter.ok || !(await publicAfter.text()).includes(`${prefix} Özel`)) throw new Error('Public menu did not refresh after commit')
  await page.getByRole('textbox', { name: 'Ürün veya kategori ara' }).fill('')
  await page.getByRole('button', { name: 'Toplu işlem geçmişi', exact: true }).click()
  await expect(dialog.getByText(owner.user!.email!, { exact: true })).toBeVisible()
  await expect(dialog.getByText('İşletme sahibi', { exact: true })).toBeVisible()
  await page.screenshot({ path: `${output}/desktop-history.png` })
  await page.getByRole('button', { name: 'Ayrıntılar', exact: true }).first().click()
  await expect(dialog.getByText(owner.user!.email!, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Bu işlemi geri al', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'İşlemi geri al', exact: true }).click()
  await expect(dialog.getByText('İşlem geri alındı.', { exact: true })).toBeVisible({ timeout: 30000 })
  const restored = await admin.from('menu_items').select('price,name').eq('id',first.id).single()
  if (restored.data?.price !== 100 || restored.data?.name !== first.name) throw new Error('Undo failed')
  await dialog.getByRole('button', { name: 'Kapat', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Menü işlemleri', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Tüm ürünleri düzenle (70)', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Toplu işlem ayarları', exact: true }).click()
  await dialog.locator('#bulk-rule-field').click()
  await page.getByRole('option', { name: 'Açıklama', exact: true }).click()
  await dialog.locator('#bulk-rule-mode').click()
  await page.getByRole('option', { name: 'Ortak açıklama', exact: true }).click()
  await dialog.getByLabel('Yeni metin', { exact: true }).fill('Mobil düzenleme')
  await dialog.getByRole('button', { name: '70 ürüne uygula', exact: true }).click()
  await expect(dialog.locator(`#bulk-description-${first.id}`)).toHaveValue('Mobil düzenleme')
  await expect(dialog.locator('#bulk-rule-field')).not.toBeVisible()
  await page.setViewportSize({ width: 700, height: 950 })
  await expect.poll(async () => (await dialog.boundingBox())?.width ?? 0, { message: 'Tablet dialog must use the available width' }).toBeGreaterThan(650)
  await page.setViewportSize({ width: 1100, height: 950 })
  await expect(dialog.locator('#bulk-rule-field')).toBeVisible()
  await page.screenshot({ path: `${output}/tablet-edit.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await dialog.getByRole('button', { name: 'Toplu işlem ayarları', exact: true }).click()
  await expect(dialog.locator('#bulk-rule-field')).not.toBeVisible()
  await page.screenshot({ path: `${output}/mobile-edit.png` })
  if (await dialog.evaluate(element => element.scrollWidth > element.clientWidth)) throw new Error('Mobile dialog overflows horizontally')
  await dialog.getByRole('button', { name: 'Değişiklikleri incele', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '70 ürünü güncelle', exact: true })).toBeVisible({ timeout: 30000 })
  await page.screenshot({ path: `${output}/mobile-preview.png` })
  // A concurrent edit after preview cannot be overwritten by the bulk commit.
  const concurrent = await admin.from('menu_items').update({ price: 199 }).eq('id', first.id)
  if (concurrent.error) throw concurrent.error
  await dialog.getByRole('button', { name: '70 ürünü güncelle', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Güncel değerleri yükle', exact: true })).toBeVisible({ timeout: 30000 })
  const unchanged = await admin.from('menu_items').select('description').in('category_id', [categoryId,secondCategoryId])
  if (unchanged.error || unchanged.data.some(row => row.description !== 'Deneme açıklaması')) throw new Error('Conflict caused partial writes')
  await dialog.getByRole('button', { name: 'Güncel değerleri yükle', exact: true }).click()
  await expect(dialog.locator(`#bulk-price-${first.id}`)).toHaveValue('199,00', { timeout: 30000 })
  await expect(dialog.locator(`#bulk-description-${first.id}`)).toHaveValue('Mobil düzenleme')
  await page.screenshot({ path: `${output}/mobile-conflict-recovery.png` })
  await dialog.getByRole('button', { name: 'Değişiklikleri incele', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '70 ürünü güncelle', exact: true })).toBeVisible({ timeout: 30000 })
  await dialog.getByRole('button', { name: 'Kapat', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Değişiklikleri sil', exact: true }).click()
  if (errors.length) throw new Error(errors.join('\n'))
  writeFileSync(`${output}/result.json`, JSON.stringify({ passed: true, products: 70, scenarios: ['all-products-across-categories','selection-independent-of-search','actor-email-and-role','select-beyond-60','percentage-rule','manual-edit','draft-guard','server-preview','commit','history','undo','mobile-edit','tablet-width','responsive-rule-expansion','mobile-preview','no-overflow','public-menu-refresh','conflict-atomicity','draft-rebase'], errors },null,2))
  console.log(`Browser checks PASS: ${output}`)
} catch (error) {
  for (const context of browser.contexts()) for (const page of context.pages()) { await page.screenshot({ path: `${output}/failure.png` }).catch(() => {}); writeFileSync(`${output}/failure.txt`, await page.locator('body').innerText().catch(() => '')) }
  throw error
} finally {
  await browser.close()
  const ops = await admin.from('menu_bulk_operations').select('id,undo_of,changes').eq('restaurant_id',restaurant.id)
  const operationIds = (ops.data ?? []).filter(op => JSON.stringify(op.changes).includes(prefix)).map(op => op.id)
  if (operationIds.length) {
    const undoIds = (ops.data ?? []).filter(op => operationIds.includes(op.id) && op.undo_of).map(op => op.id)
    if (undoIds.length) await admin.from('menu_bulk_operations').delete().in('id',undoIds)
    await admin.from('menu_bulk_operations').delete().in('id',operationIds)
  }
  await admin.from('menu_items').delete().in('category_id',[categoryId,secondCategoryId])
  await admin.from('menu_categories').delete().in('id',[categoryId,secondCategoryId])
  await admin.from('billing_subscriptions').delete().eq('restaurant_id',restaurant.id)
  await admin.from('billing_customers').delete().eq('restaurant_id',restaurant.id)
  await admin.from('restaurants').delete().eq('id',restaurant.id)
}
